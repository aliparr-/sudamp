#!/bin/bash
# Vendors exactly the mpv v0.41.0 internal headers that Sources/SudampAO/*.c includes (found with clang -MM)
# into Sources/SudampAO/vendor/mpv/, then regenerates vendor/config/config.h. These headers are LGPL-2.1+.
# The pull AO depends on mpv's internal ABI, so the tag here must match the libmpv inside the pinned MPVKit
# (1.0.0 = mpv v0.41.0). Re-run this, then `make verify-binary`, whenever the MPVKit pin changes.
set -euo pipefail

MPV_TAG="v0.41.0"
MPV_TARBALL_SHA256="ee21092a5ee427353392360929dc64645c54479aefdb5babc5cfbb5fad626209"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CACHE="${SUDAMP_DEV_CACHE:-$HOME/Library/Caches/sudamp-dev}/mpv-$MPV_TAG"
TARGET="$ROOT/Sources/SudampAO"
DEST="$TARGET/vendor"

mkdir -p "$CACHE"
if [ ! -f "$CACHE/src/MPV_VERSION" ]; then
    if [ ! -f "$CACHE/mpv.tar.gz" ]; then
        curl -fsSL -o "$CACHE/mpv.tar.gz" "https://github.com/mpv-player/mpv/archive/refs/tags/$MPV_TAG.tar.gz"
    fi
    echo "$MPV_TARBALL_SHA256  $CACHE/mpv.tar.gz" | shasum -a 256 -c - >/dev/null
    rm -rf "$CACHE/src" && mkdir -p "$CACHE/src"
    tar -xzf "$CACHE/mpv.tar.gz" -C "$CACHE/src" --strip-components 1
fi
SRC="$CACHE/src"
grep -q "${MPV_TAG#v}" "$SRC/MPV_VERSION" || { echo "error: $SRC is not mpv $MPV_TAG" >&2; exit 1; }

# Discover headers with an empty stand-in config.h (only its existence matters for -MM).
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
touch "$TMP/config.h"
HEADERS=()
for c in "$TARGET"/*.c; do
    while IFS= read -r dep; do
        case "$dep" in "$SRC"/*) HEADERS+=("${dep#"$SRC"/}") ;; esac
    done < <(clang -MM -I"$SRC" -I"$SRC/audio/out" -I"$TMP" -I"$TARGET/include" "$c" | tr ' \\' '\n\n' | grep -v '^$')
done
[ "${#HEADERS[@]}" -gt 0 ] || { echo "error: no mpv headers found" >&2; exit 1; }

rm -rf "$DEST/mpv"
mkdir -p "$DEST/mpv"
for h in $(printf '%s\n' "${HEADERS[@]}" | sort -u); do
    mkdir -p "$DEST/mpv/$(dirname "$h")"
    cp "$SRC/$h" "$DEST/mpv/$h"
done
cp "$SRC/LICENSE.LGPL" "$DEST/LICENSE.LGPL"
cat > "$DEST/README.md" <<EOF
# Vendored mpv headers (LGPL-2.1-or-later)

Copied by \`scripts/vendor-mpv-headers.sh\` from mpv $MPV_TAG
(tarball sha256 \`$MPV_TARBALL_SHA256\`). Do not edit; re-run the script.
\`config/config.h\` is generated by \`scripts/gen-mpv-config.sh\`.

Files: $(printf '%s ' $(printf '%s\n' "${HEADERS[@]}" | sort -u))
EOF

"$ROOT/scripts/gen-mpv-config.sh"
echo "vendored ${#HEADERS[@]} header references ($(find "$DEST/mpv" -name '*.h' | wc -l | tr -d ' ') files) from mpv $MPV_TAG"
