#!/bin/bash
# Generates Sources/SudampAO/vendor/config/config.h for the vendored mpv headers.
# Every HAVE_* macro the vendored headers test must resolve here; an unknown one fails the script, because a
# wrong value could silently change struct layouts that the pull AO shares with the prebuilt libmpv.
# Values follow MPVKit 1.0.0's macOS meson configuration (BuildScripts/XCFrameworkBuild/main.swift at tag 1.0.0:
# -Dcocoa/-Dcoreaudio/-Davfoundation enabled, -Dlua=luajit, -Djavascript=disabled, -Dgpl=false) plus mpv's
# platform detection for macOS (posix + darwin).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VENDOR="$ROOT/Sources/SudampAO/vendor"
OUT="$VENDOR/config/config.h"

known_value() {
    case "$1" in
        HAVE_POSIX) echo 1 ;;          # macOS is POSIX
        HAVE_DARWIN) echo 1 ;;         # mp_time on Darwin uses mach_absolute_time
        HAVE_WIN32_DESKTOP) echo 0 ;;
        HAVE_ANDROID) echo 0 ;;
        HAVE_COCOA) echo 1 ;;
        HAVE_COREAUDIO) echo 1 ;;
        HAVE_AVFOUNDATION) echo 1 ;;
        HAVE_LUA) echo 1 ;;
        HAVE_JAVASCRIPT) echo 0 ;;
        HAVE_GPL) echo 0 ;;
        *) return 1 ;;
    esac
}

MACROS=$(grep -rhoE '\bHAVE_[A-Z0-9_]+' "$VENDOR/mpv" | sort -u || true)
mkdir -p "$(dirname "$OUT")"
{
    echo "/* Generated by scripts/gen-mpv-config.sh — do not edit. */"
    echo "#pragma once"
    for m in $MACROS; do
        if v=$(known_value "$m"); then
            echo "#define $m $v"
        else
            echo "error: gen-mpv-config.sh has no value for $m (tested by a vendored mpv header)" >&2
            exit 1
        fi
    done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(echo $MACROS | wc -w | tr -d ' ') macros: $(echo $MACROS))"
