def cmp(name, t):
    bad=[]; ok=0; missing=[]
    for k,v in t.items():
        if k not in W: missing.append(k); continue
        wv=W[k]; ww=(wv['x'],wv['y'],wv['w'],wv['h'])
        if ww==v: ok+=1
        else: bad.append((k, 'port', v, 'webamp', ww))
    print(f"== {name}: {len(t)} mapped, {ok} identical, {len(bad)} differ, unmapped-name {missing}")
    for x in bad: print("  ", *x)
